// Helper to construct EvaluationRecord from the pre-defined 28-student batch data
export function generate28StudentBatchRecords(): EvaluationRecord[] {
  return CLASS_30_STUDENTS_SAMPLE_DATA.map((item, idx) => {
    const total = item.scores.body1 + item.scores.body2 + item.scores.language + item.scores.wordCount;
    const contentRating = Math.min(5, Math.max(2, Math.round((item.scores.body1 + item.scores.body2) / 1.6)));
    const languageRating = Math.min(5, Math.max(2, Math.round((item.scores.language / 4) * 5)));
    const volumeRating = Math.min(5, Math.max(2, Math.round((item.scores.wordCount / 4) * 5)));

    const stars = (r: number) => '★'.repeat(r) + '☆'.repeat(5 - r);

    return {
      id: `batch-student-${idx + 1}`,
      studentInfo: item.studentInfo,
      scores: {
        body1Score: item.scores.body1,
        body2Score: item.scores.body2,
        languageScore: item.scores.language,
        wordCountScore: item.scores.wordCount,
        totalScore: total,
      },
      extractedText: item.text,
      wordCount: item.wordCount,
      rubricNotes: {
        body1Note: `본문 1(하는 일/특징): ${item.scores.body1}점 배점 기준 충족`,
        body2Note: `본문 2(선정이유/배운점): ${item.scores.body2}점 배점 기준 충족`,
        languageNote: `언어형식(분사수식+because): ${item.scores.language}점`,
        wordCountNote: `글의 구성: ${item.wordCount}단어 (${item.scores.wordCount}점)`,
      },
      teacherMemo: item.memo,
      neisNote: item.neis,
      studentFeedback: {
        achievementLevels: {
          contentRating,
          contentStars: stars(contentRating),
          languageRating,
          languageStars: stars(languageRating),
          volumeRating,
          volumeStars: stars(volumeRating),
          wordCountNote: `총 ${item.wordCount}단어`,
        },
        goodPoints: item.goodPoints,
        betterExpressions: [
          {
            original: item.text.split('.')[1]?.trim() || item.text.slice(0, 50),
            improved: `Furthermore, ${item.text.split('.')[1]?.trim() || 'they carry out their duties with pride.'}`,
            reason: '문장 간 연결사(Furthermore, In addition)를 보완하면 글의 문맥적 흐름이 한결 세련되어집니다.',
          },
        ],
        nextStep:
          item.wordCount >= 80
            ? '다양한 접속부사(However, Consequently)와 고급 형용사를 시도하여 고등학교 수준의 서술형 에세이로 발전시켜 보세요!'
            : '주어-동사를 갖춘 완전한 문장을 1~2개 더 덧붙여 목표 분량(80단어 이상)을 채우는 연습을 지속해 봅시다.',
      },
      analyzedAt: `2026-09-15 11:${String(10 + Math.floor(idx / 2)).padStart(2, '0')}`,
      sourceType: 'sample',
    };
  });
}
